from datetime import datetime, timezone
from typing import Literal
from pydantic import BaseModel, Field
from app.schemas.content import ContentPiece, QualityCheckResult

WorkerStatus = Literal["idle", "queued", "running", "needs_approval", "completed", "failed", "paused"]
TaskPriority = Literal["low", "medium", "high", "critical"]

class TaskRequest(BaseModel):
    worker_id: str = Field(description="Target worker identifier")
    objective: str = Field(min_length=8, max_length=2000, description="Task directive or content brief")
    require_approval: bool = Field(default=True, description="Enforce human approval before publishing")
    target_platform: Literal["instagram", "youtube_shorts", "x", "facebook"] = Field(
        default="instagram", description="Target distribution channel"
    )

class TaskPlan(BaseModel):
    """Strategic plan generated by Master Agent prior to execution."""
    priority: TaskPriority = "medium"
    rationale: str = ""
    estimated_tokens: int = 1500
    approval_gates: list[str] = Field(default_factory=lambda: ["content_review", "factuality_check"])

class TaskReport(BaseModel):
    """Comprehensive structured execution report."""
    task_id: str
    worker_id: str
    worker_name: str
    objective: str
    status: WorkerStatus
    content: ContentPiece | None = None
    output: str | None = None
    quality_check: QualityCheckResult | None = None
    approval_required: bool = True
    priority: TaskPriority = "medium"
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

